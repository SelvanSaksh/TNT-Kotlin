/** Brand mark and chip colour for one social platform. */
data class SocialBrand(
    val icon: ImageVector,
    val color: Color,
)

/**
 * Resolves a CMS `platform` value, or the link itself, to a brand mark. The CMS
 * is inconsistent about which of the two it fills in, so both are checked.
 */
fun socialBrandFor(platform: String?, url: String?): SocialBrand? {
    val hint = (platform.orEmpty() + " " + url.orEmpty()).lowercase()
    return when {
        "facebook" in hint || "fb.com" in hint || "fb.me" in hint -> SocialBrand(FacebookMark, Color(0xFF1877F2))
        "instagram" in hint || "instagr.am" in hint -> SocialBrand(InstagramMark, Color(0xFFE1306C))
        "youtube" in hint || "youtu.be" in hint -> SocialBrand(YouTubeMark, Color(0xFFFF0000))
        "twitter" in hint || "x.com" in hint || hint.trim() == "x" -> SocialBrand(XMark, Color(0xFF000000))
        "linkedin" in hint -> SocialBrand(LinkedInMark, Color(0xFF0A66C2))
        "whatsapp" in hint || "wa.me" in hint -> SocialBrand(WhatsAppMark, Color(0xFF25D366))
        "telegram" in hint || "t.me" in hint -> SocialBrand(TelegramMark, Color(0xFF26A5E4))
        "pinterest" in hint || "pin.it" in hint -> SocialBrand(PinterestMark, Color(0xFFBD081C))
        "tiktok" in hint -> SocialBrand(TikTokMark, Color(0xFF010101))
        "snapchat" in hint -> SocialBrand(SnapchatMark, Color(0xFFFFFC00))
        "threads" in hint -> SocialBrand(ThreadsMark, Color(0xFF000000))
        "reddit" in hint -> SocialBrand(RedditMark, Color(0xFFFF4500))
        "mailto:" in hint || "email" in hint -> SocialBrand(EmailMark, Color(0xFF64748B))
        "tel:" in hint || "phone" in hint || "call" in hint -> SocialBrand(PhoneMark, Color(0xFF16A34A))
        url.isNullOrBlank() -> null
        else -> SocialBrand(WebsiteMark, Color(0xFF4338CA))
    }
}

private fun brandVector(name: String, vararg paths: String): ImageVector =
    ImageVector.Builder(
        name = name,
        defaultWidth = 24.dp,
        defaultHeight = 24.dp,
        viewportWidth = 24f,
        viewportHeight = 24f,
    ).apply {
        paths.forEach { path ->
            addPath(
                pathData = PathParser().parsePathString(path).toNodes(),
                fill = SolidColor(Color.White),
            )
        }
    }.build()

